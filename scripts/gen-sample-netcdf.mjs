#!/usr/bin/env node
// Generates docs/examples/sample.nc — a deterministic NetCDF-3 classic climate dataset with
// complete fixed-size variable payloads. The previous sample stopped at its header and pointed
// every variable at byte zero.
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const NC_DIMENSION = 10;
const NC_VARIABLE = 11;
const NC_ATTRIBUTE = 12;
const NC_CHAR = 2;
const NC_FLOAT = 5;

const u32 = (value) => {
  const output = Buffer.alloc(4);
  output.writeUInt32BE(value >>> 0);
  return output;
};
const pad4 = (value) => Buffer.concat([value, Buffer.alloc((4 - value.length % 4) % 4)]);
const ncString = (value) => {
  const bytes = Buffer.from(value, 'utf8');
  return Buffer.concat([u32(bytes.length), pad4(bytes)]);
};
const absent = () => Buffer.alloc(8);
const charAttribute = (name, value) => {
  const bytes = Buffer.from(value, 'utf8');
  return Buffer.concat([ncString(name), u32(NC_CHAR), u32(bytes.length), pad4(bytes)]);
};
const attributeList = (attributes) => attributes.length
  ? Buffer.concat([u32(NC_ATTRIBUTE), u32(attributes.length), ...attributes.map(([name, value]) => charAttribute(name, value))])
  : absent();
const floatData = (values) => {
  const output = Buffer.alloc(values.length * 4);
  values.forEach((value, index) => output.writeFloatBE(value, index * 4));
  return output;
};

const dimensions = [
  ['time', 3],
  ['latitude', 4],
  ['longitude', 6],
];
const times = [0, 6, 12];
const latitudes = [-45, -15, 15, 45];
const longitudes = [0, 60, 120, 180, 240, 300];
const temperature = [];
const pressure = [];
for (let t = 0; t < times.length; t++) {
  for (const latitude of latitudes) {
    for (const longitude of longitudes) {
      temperature.push(273.15 + t * 1.75 + (45 - Math.abs(latitude)) * 0.18 + Math.cos(longitude * Math.PI / 180) * 2.5);
      pressure.push(1013.25 - Math.abs(latitude) * 0.7 - t * 1.5 + Math.sin(longitude * Math.PI / 180) * 4);
    }
  }
}

const variables = [
  { name: 'time', dims: [0], attrs: [['units', 'hours since 2026-01-01 00:00:00 UTC'], ['long_name', 'forecast time']], data: floatData(times) },
  { name: 'latitude', dims: [1], attrs: [['units', 'degrees_north'], ['standard_name', 'latitude']], data: floatData(latitudes) },
  { name: 'longitude', dims: [2], attrs: [['units', 'degrees_east'], ['standard_name', 'longitude']], data: floatData(longitudes) },
  { name: 'temperature', dims: [0, 1, 2], attrs: [['units', 'K'], ['long_name', 'air temperature']], data: floatData(temperature) },
  { name: 'pressure', dims: [0, 1, 2], attrs: [['units', 'hPa'], ['long_name', 'surface pressure']], data: floatData(pressure) },
];

const dimensionList = Buffer.concat([
  u32(NC_DIMENSION),
  u32(dimensions.length),
  ...dimensions.flatMap(([name, size]) => [ncString(name), u32(size)]),
]);
const globalAttributes = attributeList([
  ['title', 'File Viewer Demo Climate Dataset'],
  ['institution', 'File Viewer Demo Institute'],
  ['source', 'Deterministic synthetic gridded observations'],
  ['history', 'Generated by scripts/gen-sample-netcdf.mjs'],
  ['Conventions', 'CF-1.10'],
]);

function variableList(begins) {
  const definitions = variables.map((variable, index) => Buffer.concat([
    ncString(variable.name),
    u32(variable.dims.length),
    ...variable.dims.map(u32),
    attributeList(variable.attrs),
    u32(NC_FLOAT),
    u32(variable.data.length),
    u32(begins[index] || 0),
  ]));
  return Buffer.concat([u32(NC_VARIABLE), u32(variables.length), ...definitions]);
}

const prefix = Buffer.concat([Buffer.from([0x43, 0x44, 0x46, 0x01]), u32(0), dimensionList, globalAttributes]);
const provisionalHeader = Buffer.concat([prefix, variableList(variables.map(() => 0))]);
const begins = [];
let dataOffset = provisionalHeader.length;
for (const variable of variables) {
  begins.push(dataOffset);
  dataOffset += variable.data.length + (4 - variable.data.length % 4) % 4;
}
const header = Buffer.concat([prefix, variableList(begins)]);
if (header.length !== provisionalHeader.length) throw new Error('NetCDF header size changed while assigning offsets');

const payloads = variables.map((variable) => pad4(variable.data));
const output = Buffer.concat([header, ...payloads]);
const destination = join(new URL('../docs/examples/', import.meta.url).pathname, 'sample.nc');
await writeFile(destination, output);
console.log(`Wrote ${destination} (${output.length} bytes, ${variables.length} populated variables)`);
