// Sokoban level-set registry. Sokoban is a FAMILY of level sets behind an in-game picker (the chosen
// set persists in localStorage). This file is METADATA ONLY — id, display name, level COUNT (a static
// literal), and lazy loaders. NO level/solution module is imported at load time: opening the game would
// otherwise fetch all ~18 set files (~250 KB) up front and lag. Instead sokoban.js loads the current
// set's levels to display, then background-prefetches the rest (see its prefetchRest()). Each set is a
// sokoban-<id>-levels.js / sokoban-<id>-solutions.js pair (the base Microban set uses the unprefixed
// names). `solutions` may be shorter/empty than `levels` — the Solve button degrades gracefully. Every
// set's stored solutions are replayed by tests/sokoban-levels.test.mjs (which also asserts each `count`
// matches the real LEVELS length, so a hard-coded count can't silently drift). `maxPending` caps how
// many levels may lack a solution (default 2); the all-pending "Unsolved Challenges" set raises it.
const set = (id, name, count, base, extra = {}) => ({
  id, name, count, ...extra,
  loadLevels: () => import('./sokoban-' + base + 'levels.js').then((m) => m.LEVELS),
  loadSolutions: () => import('./sokoban-' + base + 'solutions.js').then((m) => m.SOLUTIONS),
});

