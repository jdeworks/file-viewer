// heat.js — Stage 8 Entropy Field: the THERMAL resource (pure, deterministic, no DOM/rng).
//
// Heat is the second pressure axis (Frostpunk's dual-axis lesson). Active nodes generate heat —
// hotter the deeper the zone, doubled under High-Load; the field passively vents a baseline, plus
// any coolant structures (plugged in by structures.js later via ventFromStructures). Heat ABOVE a
// threshold couples back into decay (thermalDecayBonus) and into entropy%, so a player who runs the
// field hot for output pays for it in faster collapse. engine.js calls computeHeatDelta at the end
// of a cycle (from post-decay node statuses) and thermalDecayBonus inside the decay loop (using the
// heat carried in from the prior cycle).

import { nodeById } from "./nodes.js";

export const HEAT_CAP = 100;
export const THERMAL_THRESHOLD = 55;   // heat above this starts amplifying decay
export const BASE_VENT = 9;            // passive cooling per cycle

// Per-tier heat generated by an online, non-failed node each cycle (frontier runs hottest).
const TIER_HEAT = { 1: 1, 2: 1.5, 3: 2.5, 4: 3.5 };

// Extra venting from tech (Heat Sinks/Cryo Loop → heatVentBonus) and placed Heat Sink structures
// (structHeatVent). Both are plain numeric fields folded by tech.js / structures.js.
export function ventFromStructures(state) {
  return Math.max(0, Number(state.heatVentBonus || 0)) + Math.max(0, Number(state.structHeatVent || 0));
}

// Venting from online, non-failed COOLANT nodes (their whole job). A degrading loop vents at half.
export function ventFromCoolantNodes(state, statusOf, isOnline = () => true) {
  let vent = 0;
  for (const n of state.nodes) {
    if (!isOnline(n)) continue;
    const def = nodeById(n.id) || {};
    if (def.zone !== "coolant") continue;
    const s = statusOf(n.health);
    if (s === "failed") continue;
    vent += (def.coolantVent || 0) * (s === "degrading" ? 0.5 : 1);
  }
  return vent;
}

// Heat generated this cycle from the live node statuses. `isOnline` lets the caller exclude sectors
// that have not been brought online yet (defaults to everything online).
export function heatGeneration(state, statusOf, isOnline = () => true) {
  let gen = 0;
  for (const n of state.nodes) {
    if (!isOnline(n)) continue;
    const s = statusOf(n.health);
    if (s === "failed") continue;
    const def = nodeById(n.id) || {};
    let h = TIER_HEAT[def.tier] || 1;
    if (state.highLoad && state.highLoad[n.id] && def.supportsHighLoad) h *= 2;
    if (s === "degrading") h *= 0.5; // a degrading node draws less load, runs cooler
    gen += h;
  }
  return gen;
}

// The net heat change for a cycle: generation minus (baseline + structural) venting.
export function computeHeatDelta(state, statusOf, isOnline) {
  const gen = heatGeneration(state, statusOf, isOnline);
  const vent = BASE_VENT + ventFromStructures(state) + ventFromCoolantNodes(state, statusOf, isOnline);
  return { gen: round1(gen), vent: round1(vent), delta: round1(gen - vent) };
}

// Extra per-node health loss when the field is hot. 0 below the threshold; climbs to ~+3 at cap. The
// threshold is raised by the Thermal Throttle tech (engine passes the effective value).
export function thermalDecayBonus(heat, threshold = THERMAL_THRESHOLD) {
  const t = Math.min(HEAT_CAP - 1, Number(threshold) || THERMAL_THRESHOLD);
  const over = Math.max(0, Number(heat || 0) - t);
  return over / (HEAT_CAP - t) * 3;
}

// Heat's contribution to the entropy readout (over-threshold heat reads as instability).
export function thermalEntropy(heat, threshold = THERMAL_THRESHOLD) {
  const t = Number(threshold) || THERMAL_THRESHOLD;
  return Math.max(0, Number(heat || 0) - t) / 2;
}

export function clampHeat(v) {
  return Math.max(0, Math.min(HEAT_CAP, Number(v) || 0));
}

function round1(v) {
  return Math.round(v * 10) / 10;
}
