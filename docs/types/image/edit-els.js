// Image-editor DOM lookups. The renderer's toolbar is ~75 `.imgv-*` controls; collecting the
// querySelector calls here keeps the renderer focused on behaviour. Returns ONE flat bag the
// renderer destructures — names match the renderer's locals 1:1, so the renderer body is unchanged.
// Edit-only controls are null when !canEdit (the tool modules are null-safe), exactly as before.
