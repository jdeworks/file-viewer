function esc(s) { return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

function parseGcode(text) {
  const lines = text.split(/\r?\n/);
  let printTime = null, filamentMm = null, layerCount = 0, layerHeight = null;
  let slicer = null, nozzleTemp = null, bedTemp = null;
  let xMax = 0, yMax = 0, zMax = 0;

  const slicerPatterns = [
    [/Generated by PrusaSlicer\s*([\d.]+)/i, (m) => 'PrusaSlicer ' + m[1]],
    [/Cura_SteamEngine\s*([\d.]+)/i, (m) => 'Ultimaker Cura ' + m[1]],
    [/Simplify3D/i, () => 'Simplify3D'],
    [/IdeaMaker/i, () => 'IdeaMaker'],
    [/OrcaSlicer/i, () => 'OrcaSlicer'],
    [/BambuStudio/i, () => 'BambuStudio'],
    [/Slic3r/i, () => 'Slic3r'],
    [/KISSlicer/i, () => 'KISSlicer'],
    [/SuperSlicer/i, () => 'SuperSlicer'],
  ];

  for (const line of lines) {
    const trimmed = line.trim();

    if (trimmed.startsWith(';')) {
      const comment = trimmed.slice(1).trim();

      if (!slicer) {
        for (const [pat, fmt] of slicerPatterns) {
          const m = comment.match(pat);
          if (m) { slicer = fmt(m); break; }
        }
      }

      if (!printTime) {
        const m = comment.match(/estimated printing time[^=:]*[=:]\s*(.+)/i)
          || comment.match(/print_time\s*=\s*(.+)/i);
        if (m) printTime = m[1].trim();
      }

      if (!filamentMm) {
        const m = comment.match(/filament used \[mm\]\s*=\s*([\d.]+)/i)
          || comment.match(/filament_used_mm\s*=\s*([\d.]+)/i);
        if (m) filamentMm = parseFloat(m[1]);
      }

      if (!layerHeight) {
        const m = comment.match(/layer_height\s*=\s*([\d.]+)/i);
        if (m) layerHeight = parseFloat(m[1]);
      }

      if (/^LAYER:\d+/i.test(comment) || /^layer_number\s*=\s*\d+/i.test(comment) || /^Layer #\d+/i.test(comment)) {
        layerCount++;
      }

      continue;
    }

    const upper = trimmed.toUpperCase();

    if (!nozzleTemp) {
      const m = upper.match(/^M1(?:04|09)\s+S(\d+)/);
      if (m) nozzleTemp = parseInt(m[1]);
    }

    if (!bedTemp) {
      const m = upper.match(/^M1(?:40|90)\s+S(\d+)/);
      if (m) bedTemp = parseInt(m[1]);
    }

    if (/^G[01]\s/i.test(upper)) {
      const x = upper.match(/X([\d.]+)/); if (x && parseFloat(x[1]) > xMax) xMax = parseFloat(x[1]);
      const y = upper.match(/Y([\d.]+)/); if (y && parseFloat(y[1]) > yMax) yMax = parseFloat(y[1]);
      const z = upper.match(/Z([\d.]+)/); if (z && parseFloat(z[1]) > zMax) zMax = parseFloat(z[1]);
    }
  }

  return { printTime, filamentMm, layerCount, layerHeight, slicer, nozzleTemp, bedTemp, xMax, yMax, zMax };
}

function highlightLine(line) {
  if (!line.trim()) return '';
  const commentIdx = line.indexOf(';');
  let code = commentIdx >= 0 ? line.slice(0, commentIdx) : line;
  const comment = commentIdx >= 0 ? line.slice(commentIdx) : '';

  code = code.replace(/\b(G\d+)\b/g, '<span style="color:#7ec8e3">$1</span>');
  code = code.replace(/\b(M\d+)\b/g, '<span style="color:#e8a87c">$1</span>');

  const commentHtml = comment ? '<span style="color:var(--fg2)">' + esc(comment) + '</span>' : '';
  return esc(code).replace(/&lt;span/g, '<span').replace(/style=&quot;/g, 'style="').replace(/&quot;&gt;/g, '">').replace(/&lt;\/span&gt;/g, '</span>') + commentHtml;
}

function fmtMm(mm) {
  if (mm == null) return null;
  if (mm >= 1000) return (mm / 1000).toFixed(2) + ' m';
  return mm.toFixed(1) + ' mm';
}

function row(label, value) {
  if (value == null || value === '' || value === 0) return '';
  return '<dt style="color:var(--fg2);font-size:11px;margin:0;padding:2px 0">' + esc(label) + '</dt>'
    + '<dd style="color:var(--fg);margin:0 0 8px 0;padding:0">' + esc(String(value)) + '</dd>';
}

export async function render(intake, _ctx) {
  const text = intake.text || '';
  const meta = parseGcode(text);

  const rows = [
    row('Slicer', meta.slicer),
    row('Print time', meta.printTime),
    row('Filament used', fmtMm(meta.filamentMm)),
    row('Layer count', meta.layerCount || null),
    row('Layer height', meta.layerHeight != null ? meta.layerHeight + ' mm' : null),
    row('Nozzle temp', meta.nozzleTemp != null ? meta.nozzleTemp + '°C' : null),
    row('Bed temp', meta.bedTemp != null ? meta.bedTemp + '°C' : null),
    row('Est. width', meta.xMax > 0 ? meta.xMax.toFixed(1) + ' mm' : null),
    row('Est. depth', meta.yMax > 0 ? meta.yMax.toFixed(1) + ' mm' : null),
    row('Est. height', meta.zMax > 0 ? meta.zMax.toFixed(1) + ' mm' : null),
  ].filter(Boolean).join('');

  const card = rows
    ? '<dl style="display:grid;grid-template-columns:max-content 1fr;gap:0 16px;margin:0 0 16px 0;padding:12px 16px;border:1px solid var(--border);border-radius:6px;font-size:13px">' + rows + '</dl>'
    : '';

  const preview = text.split(/\r?\n/).slice(0, 200);
  const highlighted = preview.map((line) => {
    const commentIdx = line.indexOf(';');
    let code = commentIdx >= 0 ? line.slice(0, commentIdx) : line;
    const comment = commentIdx >= 0 ? line.slice(commentIdx) : '';

    let codePart = esc(code)
      .replace(/\b(G\d+)\b/g, '<span style="color:#7ec8e3">$1</span>')
      .replace(/\b(M\d+)\b/g, '<span style="color:#e8a87c">$1</span>');

    const commentPart = comment ? '<span style="color:var(--fg2)">' + esc(comment) + '</span>' : '';
    return codePart + commentPart;
  }).join('\n');

  const truncNote = text.split(/\r?\n/).length > 200
    ? '<p style="color:var(--fg2);font-size:12px;margin:8px 0 0 0">Showing first 200 lines of ' + text.split(/\r?\n/).length + ' total.</p>'
    : '';

  const bodyHtml = '<div class="gcode-wrap" style="padding:16px;font-family:monospace">'
    + card
    + '<pre style="margin:0;overflow:auto;font-size:12px;line-height:1.5;color:var(--fg)">' + highlighted + '</pre>'
    + truncNote
    + '</div>';

  return { bodyHtml, hadUnsafe: false };
}
